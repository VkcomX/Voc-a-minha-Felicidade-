let music = null;

let musicPlaying = false;


function toggleMusic() {

if (!music) {

music = new Audio("golden.mp3");

music.loop = true;

}


if (musicPlaying) {

music.pause();

musicPlaying = false;

showToast(
"Nossa música pausada ♡"
);

}

else {

music.play()

.then(() => {

musicPlaying = true;

showToast(
"Tocando Golden 🎵"
);

})

.catch(() => {

showToast(
"Coloque o arquivo golden.mp3 na pasta do site."
);

});

}

}


// ==============================
